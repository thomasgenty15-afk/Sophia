-- FF-038 · LE RÉFÉRENTIEL DE COMPOSITION
--
-- Fiche: docs/fonctionnalites/composition-des-repas/FF-038-le-referentiel-de-composition.md
-- Design d'origine: scratchpad/DESIGN-UNITES-DE-COMPOSITION.md §2.1
--
-- CE QUE CES DEUX TABLES RENDENT POSSIBLE
-- ---------------------------------------
-- Le produit ne sait pas ce qu'il met dans l'assiette. `DishIngredient` porte
-- une prose libre (`term`, `quantity`) et un booléen calculé (`in_pantry`);
-- aucun chemin du dépôt ne va de « 400 g de cuisses de poulet » à une grandeur
-- quelconque. `food_items` est un catalogue de LIBELLÉS pour l'écran du coach:
-- il porte un `typical_amount`, c'est-à-dire la taille d'une portion, et pas
-- une densité d'aliment. Les deux tables coexistent, partagent leurs slugs là
-- où c'est vrai, et ne se remplacent pas.
--
-- CE QUE CES TABLES NE FONT PAS, ET C'EST LE POINT DE L'ÉTAPE
-- ------------------------------------------------------------
-- Rien. Aucun prompt ne change, aucun parseur ne change, aucune assiette ne
-- change. Cette migration installe un INSTRUMENT DE MESURE, dont la première
-- sortie est un chiffre — la couverture de résolution — qui décide si la suite
-- du chantier (verdicts, boucle de correction) a le droit de démarrer.
--
-- LA SOURCE, ET CE QU'ELLE VAUT
-- -----------------------------
-- ANSES-CIQUAL 2020, XML, licence Etalab, via data.gouv.fr. Le script
-- d'extraction est gardé dans `scratchpad/gen_composition_seed.py` avec son
-- catalogue curé (`ciqual_catalogue.py`): un seed écrit à la main est un seed
-- que personne ne sait régénérer, et celui-ci se rejoue.
--
-- 192 des 208 entrées viennent de Ciqual. Les 16 autres portent
-- `source = 'manual'` parce que Ciqual 2020 ne les contient pas (skyr, cottage
-- cheese, halloumi, huile de coco, graines de courge…). Un référentiel n'est
-- pas moins honnête parce qu'il a deux sources; il l'est quand il ne dit pas
-- laquelle — d'où la colonne.
--
-- L'ÉNERGIE EST PARFOIS CALCULÉE, ET C'EST FIDÈLE
-- -----------------------------------------------
-- Ciqual laisse le champ énergie VIDE pour ~28 % de ses aliments (le miel en
-- fait partie) tout en donnant les macronutriments qui servent à le calculer.
-- L'extraction applique alors l'arithmétique que la constante porte dans son
-- propre nom — « Energie, Règlement UE N° 1169/2011 »: 4 kcal/g pour les
-- protéines et les glucides, 9 pour les lipides, 2 pour les fibres. Ce n'est
-- pas une invention, c'est la définition réglementaire.
--
-- CE QUI N'EST PAS ICI, ET NE LE SERA PAS
-- ---------------------------------------
-- Aucun milligramme de micronutriment. La variance sol/saison/cuisson est de
-- ±30-50 %, et le booléen « source de » est la seule granularité honnête. Les
-- seuils sont ceux du Règlement (CE) 1924/2006 — 15 % de la VNR pour 100 g —
-- appliqués aux teneurs Ciqual. La vitamine D sort entièrement du moteur: elle
-- n'est pas couvrable par l'aliment, c'est un drapeau côté coach.
-- ============================================================================

create table if not exists public.food_composition_refs (
  -- Le slug REPREND ceux de `food_items` là où l'aliment existe des deux côtés
  -- (`chicken_breast`, `salmon`, `oats`…). Pas de FK entre les deux tables:
  -- l'une est un catalogue d'écran qui peut perdre une ligne sans que la
  -- composition d'un aliment cesse d'exister, et l'inverse est vrai aussi.
  slug text primary key,

  -- LE VOCABULAIRE EXISTANT, PAS UN SECOND. Les trente groupes de
  -- `food_groups` portent déjà la FK, le seed, le token-lint et le prompt de
  -- vision. Ce dépôt a payé une duplication de vocabulaire alimentaire; on ne
  -- la refait pas pour une table de composition.
  food_group_ref text not null references public.food_groups(slug),

  label text not null check (length(btrim(label)) between 1 and 80),

  -- ── LA PROVENANCE, SUR LA LIGNE ────────────────────────────────────────
  -- `ciqual_code` et `ciqual_name` disent EXACTEMENT de quelle ligne ANSES la
  -- valeur sort. Ils ne sont pas décoratifs: Ciqual 2020 n'a pas d'énergie
  -- pour beaucoup de formes CRUES (« Brocoli, cru » n'en porte aucune), et
  -- l'extraction retient alors la forme qui en a. Sans le nom retenu, personne
  -- ne peut relire pourquoi le brocoli du référentiel vient d'une ligne
  -- « cuit à l'eau » — et c'est le genre d'écart qu'on veut pouvoir juger.
  source text not null check (source in ('ciqual', 'manual')),
  ciqual_code text,
  ciqual_name text,

  -- ── POUR 100 g CRUS ────────────────────────────────────────────────────
  -- CRUS, et c'est LE piège du domaine: « 100 g de riz » vaut ~350 kcal cru et
  -- ~130 cuit. Le passage cuit→cru se fait par `yield_class`, dans le module,
  -- et il est testé nommément.
  energy_kcal numeric not null check (energy_kcal >= 0),
  -- NULLABLES, et jamais mis à zéro. Ciqual ne donne pas toujours les lipides
  -- d'un céleri. `null` se lit « on ne sait pas »; `0` se lirait « il n'y en a
  -- pas », ce qui est une affirmation que personne n'a faite. Le module
  -- propage l'inconnu (FF-038 R2).
  protein_g numeric check (protein_g >= 0),
  carbs_g numeric check (carbs_g >= 0),
  fat_g numeric check (fat_g >= 0),
  fiber_g numeric check (fiber_g >= 0),

  -- ── LES SENTINELLES, EN BOOLÉENS ───────────────────────────────────────
  -- Présence/absence, jamais des mg. Seuils: 15 % de la VNR pour 100 g
  -- (Règlement CE 1924/2006) — calcium 120 mg, fer 2,1 mg, zinc 1,5 mg,
  -- iode 22,5 µg, B12 0,375 µg, folates 30 µg.
  --
  -- `omega3_marine` n'a pas de VNR utilisable: le seuil est EPA+DHA ≥ 0,3
  -- g/100 g, une constante OPÉRATIONNELLE choisie pour que la sentinelle
  -- veuille dire « poisson gras » (le cabillaud, ~0,2, n'en est pas un). Elle
  -- est avouée comme telle plutôt que présentée comme un seuil de littérature.
  omega3_marine boolean not null default false,
  iron_source boolean not null default false,
  calcium_source boolean not null default false,
  iodine_source boolean not null default false,
  zinc_source boolean not null default false,
  b12_source boolean not null default false,
  folate_source boolean not null default false,

  -- ── LA CUISSON ─────────────────────────────────────────────────────────
  -- La base porte la CLASSE, le module porte le FACTEUR. Éparpiller les
  -- nombres des deux côtés ferait diverger le jour où l'un des deux bouge, et
  -- c'est le module qui les teste.
  yield_class text not null check (yield_class in (
    'neutral',         -- rien n'absorbe ni ne perd
    'grain_absorbs',   -- riz, pâtes, semoule, quinoa
    'legume_absorbs',  -- légumineuses SÈCHES (une conserve est déjà hydratée)
    'meat_shrinks',    -- viandes et volailles
    'fish_shrinks',    -- poissons et fruits de mer
    'veg_shrinks'      -- légumes cuits
  )),

  -- Novotny 2012 et ses réplications: l'énergie métabolisable d'un fruit à
  -- coque ENTIER est ~72 % de sa valeur Atwater, la matrice cellulaire
  -- retenant une partie des lipides. L'effet disparaît quand la structure est
  -- détruite — les purées et beurres n'en portent pas.
  atwater_discount numeric not null default 1.0
    check (atwater_discount > 0 and atwater_discount <= 1),

  -- LA CLASSE QUI DÉCLENCHE L'ABSTENTION (FF-039 R6). Un seul terme dense non
  -- résolu suffit à rendre un repas non calculable: une matière grasse
  -- manquante déplace l'énergie d'un plat de plusieurs dizaines de pour cent,
  -- et un verdict rendu sans elle a l'air d'un résultat.
  energy_dense boolean not null default false,

  created_at timestamptz not null default now()
);


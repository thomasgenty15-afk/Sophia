-- ── LA TABLE D'ALIAS — fermée, curée, jamais générée ─────────────────────
-- Le résolveur normalise le terme du générateur (`normalizeForMatch`, le
-- normaliseur des verrous, jamais un second), tente l'égalité exacte, puis
-- cette table. Un terme qui n'y est pas reste NON RÉSOLU et compté; il ne se
-- rapproche jamais « du plus proche ».
--
-- LA PK SUR `alias` EST UNE GARDE. Deux alias en conflit (même forme
-- normalisée, deux aliments) feraient un référentiel qui rend un résultat
-- différent selon l'ordre d'insertion. Mesuré pendant la curation: « pepper »
-- désignait le poivron ET le poivre. Il a été retiré des deux listes — un
-- terme ambigu doit rester non résolu, en garder un des deux serait
-- exactement la devinette que la fiche interdit.
create table if not exists public.food_composition_aliases (
  -- DÉJÀ NORMALISÉ à l'écriture (minuscules, sans diacritiques), parce que
  -- c'est sous cette forme que le résolveur interroge. Une table qui stocke
  -- des formes brutes serait illisible par son propre lecteur.
  alias text primary key,
  slug text not null references public.food_composition_refs(slug) on delete cascade,
  -- Pourquoi cet alias existe, quand ce n'est pas évident. Un alias ajouté
  -- doit être défendable en une phrase.
  note text
);

comment on table public.food_composition_aliases is
  'FF-038: forme normalisée -> slug de composition. FERMÉE et CURÉE: un terme '
  'absent reste non résolu et compté (unresolved_terms), jamais rapproché. '
  'La curation se pilote sur resolution_coverage.';

create index if not exists food_composition_aliases_slug_idx
  on public.food_composition_aliases (slug);

-- ---------------------------------------------------------------------------
-- LES GRANTS — service-role, et rien d'autre
--
-- Supabase accorde TOUT à `authenticated` sur toute table neuve, TRUNCATE
-- compris, et TRUNCATE échappe à RLS. `revoke ... from public` ne retire PAS
-- les privilèges d'`anon`, qui les tient de son propre grant. Les deux
-- cicatrices du dépôt, retirées nommément.
--
-- RLS activée SANS AUCUNE POLITIQUE: `service_role` la contourne, tout le
-- reste se heurte à un mur. C'est de la donnée de référence, personne ne la
-- lit depuis un JWT d'élève.
-- ---------------------------------------------------------------------------
revoke all on table public.food_composition_refs from anon, authenticated;
revoke all on table public.food_composition_aliases from anon, authenticated;
alter table public.food_composition_refs enable row level security;
alter table public.food_composition_aliases enable row level security;

-- ---------------------------------------------------------------------------
-- PAS DE RÉCLAMATION RGPD, ET C'EST UNE DÉCISION ÉCRITE
--
-- Ces deux tables ne portent AUCUNE donnée d'utilisateur: pas de `user_id`,
-- pas de FK vers `auth.users`, rien qui se rapporte à une personne. Elles
-- n'entrent donc ni dans `account-export-v1` ni dans la cascade de
-- suppression.
--
-- Le dépôt a la cicatrice INVERSE — « le lifecycle ne réclame pas les tables
-- neuves », neuf tables hors export. La parade n'est pas de tout réclamer:
-- c'est que chaque table neuve DISE laquelle des deux elle est. Celle-ci le
-- dit. La table de verdicts de FF-039, qui référence des repas d'un élève,
-- dira l'inverse et sera réclamée.
-- ---------------------------------------------------------------------------


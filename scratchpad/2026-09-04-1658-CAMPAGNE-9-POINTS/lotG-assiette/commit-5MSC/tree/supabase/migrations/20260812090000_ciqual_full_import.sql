  select string_agg(a.alias, ', ') into orphans
    from public.food_composition_aliases a
    left join public.food_composition_refs r on r.slug = a.slug
   where r.slug is null;
  if orphans is not null then
    raise exception 'alias orphelins: %', left(orphans, 300);
  end if;

  -- LES ENTRÉES CURÉES À LA MAIN SURVIVENT. Elles ont été ajoutées le
  -- 2026-08-11 pour combler des trous mesurés en run réel (pita, tortilla,
  -- crispbread…), et une ligne CIQUAL homonyme ne doit pas les avoir
  -- écrasées: `on conflict do nothing` protège l'existant, ce bloc le PROUVE.
  if (select count(*) from public.food_composition_refs where source = 'manual') < 30 then
    raise exception 'des entrées curées à la main ont disparu';
  end if;

  -- Et une valeur connue n'a pas bougé.
  if not exists (
    select 1 from public.food_composition_refs
    where slug = 'chicken_breast' and energy_kcal = 110
  ) then
    raise exception 'chicken_breast a changé de valeur — l''import a écrasé';
  end if;
end;
